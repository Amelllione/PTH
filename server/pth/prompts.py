"""Промпты для выделения требований моделью. Версия меняется при любой правке текста промпта."""

EXTRACT_PROMPT_VERSION = "extract-requirements/v3"

EXTRACT_REQUIREMENTS = """Ты — аналитик требований. Найди в тексте спецификации отдельные требования и верни их списком JSON.

Типы требований:
- US — пользовательская история: «Как <роль>, хочу <действие>, чтобы <цель>» или явно описанная цель пользователя.
- FR — функциональное требование: что система обязана делать (поведение, правило, реакция на действие, ограничение).
- NFR — нефункциональное требование: качество системы (скорость, надёжность, безопасность, доступность, масштаб). Обычно содержит число или измеримый критерий.
- AC — приёмочный сценарий: как проверить, что требование выполнено («Дано… Когда… Тогда…», «проверить, что…»).

Не являются требованиями: вводные и пояснительные абзацы, определения терминов, примеры, описание текущего состояния, рекомендации и оценки, заголовки разделов, оглавление, строки таблиц, которые не задают требование, и решения, уже оформленные как ADR.

Правила:
1. Одно требование — одна проверяемая мысль. Если составное предложение содержит две независимо проверяемые части, раздели их на два требования.
2. text — формулировка, близкая к исходной. Не добавляй условий, чисел, ролей и сроков, которых нет в тексте.
3. Числа, сроки, имена и идентификаторы переноси точно, как в тексте. Не придумывай пороги и не округляй.
4. Если в тексте уже есть ID требования (например PTH-FR-012), сохрани его в начале title в квадратных скобках.
5. quote — дословная фраза из текста, на которой основано требование: без перефразирования, не длиннее 300 символов. Если подходящей цитаты нет, требование не выделяй.
6. Если требование неоднозначно или противоречит другому месту текста, всё равно включи его и добавь в конец title «(неоднозначно)».
7. Одно и то же требование не повторяй.
8. Пиши на языке исходного текста.
9. Требование — это обязательство или проверяемое поведение: в тексте есть «должен», «обязан», «не более», «не менее», «нельзя», «всегда», «никогда» или явное правило. Описание устройства, механизма или выбранного способа без такого обязательства — не требование: пропусти его.

Формат ответа: только JSON-массив, без пояснений до и после, без обёртки в markdown. Каждый элемент:
{"type": "US" | "FR" | "NFR" | "AC", "title": "краткое название до 80 символов", "text": "формулировка требования", "quote": "дословная цитата"}
Если требований нет, верни [].

Пример.
Вход: Пользователь может создать проект с уникальным ключом. Ключ состоит из латинских букв.
Ответ: [{"type": "FR", "title": "Создание проекта с уникальным ключом", "text": "Пользователь может создать проект с уникальным ключом.", "quote": "Пользователь может создать проект с уникальным ключом."}, {"type": "FR", "title": "Состав ключа проекта", "text": "Ключ проекта состоит из латинских букв.", "quote": "Ключ состоит из латинских букв."}]

Текст для анализа:
<<<
{text}
>>>"""


def render_extract(text: str) -> str:
    """Подставляет текст без str.format: в промпте есть фигурные скобки JSON."""
    return EXTRACT_REQUIREMENTS.replace("{text}", text)
